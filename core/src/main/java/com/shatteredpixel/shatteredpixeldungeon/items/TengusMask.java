import com.watabou.noosa.audio.Sample;
import com.watabou.noosa.particles.Emitter;

import java.util.ArrayList;

public class TengusMask extends Item {
	
	private static final String AC_WEAR	= "WEAR";
	
	{
		stackable = false;
		image = ItemSpriteSheet.MASK;

		defaultAction = AC_WEAR;

		unique = true;
	}
	
	@Override
	public ArrayList<String> actions( Hero hero ) {
		ArrayList<String> actions = super.actions( hero );
		actions.add( AC_WEAR );
		return actions;
	}
	
	@Override
	public void execute( Hero hero, String action ) {

		super.execute( hero, action );

		if (action.equals( AC_WEAR )) {
			
			curUser = hero;

			GameScene.show( new WndChooseSubclass( this, hero ) );
			
		}
	}
	
	@Override
	public boolean doPickUp(Hero hero, int pos) {
		Badges.validateMastery();
		return super.doPickUp( hero, pos );
	}
	
	@Override
	public boolean isUpgradable() {
		return false;
	}
	
	@Override
	public boolean isIdentified() {
		return true;
	}
	
	public void choose( HeroSubClass way ) {
		
		detach( curUser.belongings.backpack );
		Catalog.countUse( getClass() );
		
		curUser.spend( Actor.TICK );
		curUser.busy();
		
		curUser.subClass = way;
		Talent.initSubclassTalents(curUser);

		if (way == HeroSubClass.ASSASSIN && curUser.invisible > 0){
			Buff.affect(curUser, Preparation.class);
		}

		//环指大师分支技能按钮：转职时施加对应技能 buff（永久，承载右下角 ActionIndicator 按钮）
		//画廊导师无右下角按钮——技艺入口统一由大师指环（WndRingMasterArts）承担；
		//艺术之巅右下角为「艺术技艺」入口（消耗作品数值的三招专精特性）
		if (way == HeroSubClass.ART_PINNACLE){
			Buff.affect(curUser, ArtTechniques.class);
		}

		//中指 长兄「忠义巡礼者」：施加常驻特性 buff，承载右下角「复仇技艺」按钮（五式复仇技能）
		if (way == HeroSubClass.LOYAL_PILGRIM){
			Buff.affect(curUser, VengeanceArts.class);
		}

		//中指 长兄「背叛家人者」：分支特色是「攻击莱瓦汀系列之前预支账簿充能换一次力量补足」，
		//全程由 Talent.onHeroAttackStarted / onHeroAttackResolved 两条钩子驱动，
		//没有常驻 buff、也没有右下角按钮，所以这里不需要挂任何东西（保留注释以免日后误以为漏了）。
		
		curUser.sprite.operate( curUser.pos );
		Sample.INSTANCE.play( Assets.Sounds.MASTERY );
		
		Emitter e = curUser.sprite.centerEmitter();
		e.pos(e.x-2, e.y-6, 4, 4);
		e.start(Speck.factory(Speck.MASK), 0.05f, 20);
		GLog.p( Messages.get(this, "used"));
		
	}
}
